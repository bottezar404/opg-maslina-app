-- Članovi OPG-a: samo korisnici čiji je e-mail ovdje mogu vidjeti i mijenjati podatke.
create table if not exists public.members (
  email text primary key,
  name text,
  created_at timestamptz default now()
);

create or replace function public.is_member()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.members where lower(email) = lower(auth.jwt() ->> 'email'));
$$;

create table if not exists public.groves (
  id bigint generated by default as identity primary key,
  name text not null, location text, area_ha numeric check (area_ha >= 0),
  trees integer check (trees >= 0), variety text, notes text,
  created_at timestamptz default now()
);

create table if not exists public.tanks (
  id bigint generated by default as identity primary key,
  name text not null, capacity_l numeric check (capacity_l >= 0), oil_type text, notes text,
  created_at timestamptz default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null, phone text, email text, address text, notes text,
  created_at timestamptz default now()
);

create table if not exists public.harvests (
  id bigint generated by default as identity primary key,
  date date not null, grove_id bigint references public.groves(id) on delete set null,
  kg numeric not null check (kg >= 0), workers integer check (workers >= 0),
  hours numeric check (hours >= 0), notes text,
  created_at timestamptz default now()
);

create table if not exists public.millings (
  id bigint generated by default as identity primary key,
  date date not null, mill text,
  kg_olives numeric not null check (kg_olives >= 0), kg_oil numeric check (kg_oil >= 0),
  liters_oil numeric not null check (liters_oil >= 0),
  cost numeric check (cost >= 0), tank_id bigint references public.tanks(id) on delete set null, notes text,
  created_at timestamptz default now()
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  date date not null, customer_id bigint references public.customers(id) on delete set null,
  tank_id bigint references public.tanks(id) on delete set null, product text,
  liters numeric not null check (liters >= 0), price_per_l numeric not null check (price_per_l >= 0),
  paid boolean not null default false, notes text,
  created_at timestamptz default now()
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  date date not null, category text, description text,
  amount numeric not null check (amount >= 0),
  created_at timestamptz default now()
);

-- Pokloni / donacije: ulje koje se daje bez naplate
create table if not exists public.gifts (
  id bigint generated by default as identity primary key,
  date date not null, recipient text,
  tank_id bigint references public.tanks(id) on delete set null, product text,
  liters numeric not null check (liters >= 0), occasion text, notes text,
  created_at timestamptz default now()
);

-- Postavke OPG-a (npr. cijena prerade po kg maslina)
create table if not exists public.settings (
  key text primary key,
  value text,
  updated_at timestamptz default now()
);

-- Nadogradnja: količina ulja u kg (litre se računaju iz kg)
alter table public.millings add column if not exists kg_oil numeric check (kg_oil >= 0);

-- Nadogradnja: sorta kod berbe i prerade
alter table public.harvests add column if not exists variety text;
alter table public.millings add column if not exists variety text;

-- Zaštita na razini redaka (RLS): bez prijave i članstva nema pristupa ničemu.
do $$
declare t text;
begin
  foreach t in array array['groves','tanks','customers','harvests','millings','sales','expenses','gifts','settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "clanovi" on public.%I', t);
    execute format('create policy "clanovi" on public.%I for all to authenticated using (public.is_member()) with check (public.is_member())', t);
  end loop;
end $$;

alter table public.members enable row level security;
drop policy if exists "clanovi citaju" on public.members;
create policy "clanovi citaju" on public.members for select to authenticated using (public.is_member());

